type raster struct {
	img *image.RGBA
}

func hexColor(s string) color.RGBA {
	s = strings.TrimPrefix(s, "#")
	if len(s) != 6 {
		return color.RGBA{0x64, 0x74, 0x8b, 0xff}
	}
	v, _ := strconv.ParseUint(s, 16, 32)
	return color.RGBA{uint8(v >> 16), uint8(v >> 8), uint8(v), 0xff}
}

func (r raster) set(x, y int, c color.RGBA) {
	if image.Pt(x, y).In(r.img.Rect) {
		r.img.SetRGBA(x, y, c)
	}
}

func (r raster) fill(x0, y0, x1, y1 int, c color.RGBA) {
	for y := max(y0, 0); y < min(y1, r.img.Rect.Dy()); y++ {
		for x := max(x0, 0); x < min(x1, r.img.Rect.Dx()); x++ {
			r.img.SetRGBA(x, y, c)
		}
	}
}

// line draws a 2px line; dash > 0 skips alternate runs of dash pixels.
func (r raster) line(x0, y0, x1, y1 float64, c color.RGBA, dash int) {
	dx, dy := x1-x0, y1-y0
	steps := int(math.Max(math.Abs(dx), math.Abs(dy)))
	if steps == 0 {
		steps = 1
	}
	for i := 0; i <= steps; i++ {
		if dash > 0 && (i/dash)%2 == 1 {
			continue
		}
		x := int(math.Round(x0 + dx*float64(i)/float64(steps)))
		y := int(math.Round(y0 + dy*float64(i)/float64(steps)))
		r.set(x, y, c)
		r.set(x+1, y, c)
		r.set(x, y+1, c)
	}
}

// ascii keeps printable ASCII; other runes become '?'.
func ascii(s string) string {
	var b strings.Builder
	for _, r := range s {
		if r >= 0x20 && r <= 0x7E {
			b.WriteRune(r)
		} else {
			b.WriteByte('?')
		}
	}
	return b.String()
}

func textWidth(s string, scale int) int { return len(s) * 6 * scale }

func (r raster) text(x, y int, s string, c color.RGBA, scale int) {
	for i, ch := range []byte(s) {
		if ch < 0x20 || ch > 0x7E {
			ch = '?'
		}
		glyph := font5x7[ch-0x20]
		for col := 0; col < 5; col++ {
			for row := 0; row < 7; row++ {
				if glyph[col]&(1<<row) != 0 {
					r.fill(x+(i*6+col)*scale, y+row*scale, x+(i*6+col+1)*scale, y+(row+1)*scale, c)
				}
			}
		}
	}
}

// en picks the PNG label: the English name, else the ASCII original, else a
// numbered fallback.
func en(english, original, fallback string) string {
	if english != "" {
		return english
	}
	if a := ascii(original); !strings.Contains(a, "?") && a != "" {
		return a
	}
	return fallback
}

func renderPNG(s chartSpec) []byte {
	const scale = 2 // render at 2x for legible bitmap text
	W, H := chartW*scale, chartH*scale
	r := raster{img: image.NewRGBA(image.Rect(0, 0, W, H))}
	white, ink, muted, grid := color.RGBA{0xff, 0xff, 0xff, 0xff}, hexColor(chartInk), hexColor(chartMuted), hexColor(chartGridCol)
	r.fill(0, 0, W, H, white)
	l := layoutChart(s)
	px := func(x float64) float64 { return l.px(x) * scale }
	py := func(y float64) float64 { return l.py(y) * scale }
	r.text(padL*scale, 10*scale, en(s.ENTitle, s.Title, "chart"), ink, 3)
	for _, b := range s.Bands {
		fill := b.Fill
		if fill == "" {
			fill = "#f3f4f6"
		}
		r.fill(int(px(b.From)), padT*scale, int(math.Max(px(b.From)+2, px(b.To))), (padT+plotH)*scale, hexColor(fill))
	}
	for i := 0; i <= 4; i++ {
		y := l.yMax * float64(i) / 4
		r.line(padL*scale, py(y), (padL+plotW)*scale, py(y), grid, 0)
		label := fmtAxis(y)
		r.text(padL*scale-textWidth(label, 2)-8, int(py(y))-7, label, muted, 2)
	}
	r.text(8, 10*scale+30, en(s.ENYLabel, s.YLabel, ""), muted, 2)
	for _, t := range l.ticks {
		label := ascii(t.Label)
		if s.TimeAxis && s.Ticks == nil {
			label = time.UnixMilli(int64(t.X)).UTC().Format("15:04:05")
		}
		r.text(int(px(t.X))-textWidth(label, 2)/2, (padT+plotH)*scale+10, label, muted, 2)
	}
	if s.TimeAxis {
		r.text((padL+plotW)*scale-textWidth("UTC", 2), (padT+plotH)*scale+34, "UTC", muted, 2)
	}
	red := hexColor("#dc2626")
	for i, ln := range s.Lines {
		r.line(padL*scale, py(ln.Y), (padL+plotW)*scale, py(ln.Y), red, 10)
		label := en(ln.En, ln.Label, "")
		r.text((padL+plotW)*scale-textWidth(label, 2)-6, int(py(ln.Y))-18-(i%2)*18, label, red, 2)
	}
	for i, se := range s.Series {
		c := hexColor(se.Color)
		if se.Color == "" {
			c = hexColor(chartColors[i%len(chartColors)])
		}
		dash := 0
		if se.Dashed {
			dash = 8
		}
		var last *xy
		for j := range se.Points {
			p := se.Points[j]
			if !p.Valid {
				last = nil
				continue
			}
			if last != nil {
				r.line(px(last.X), py(last.Y), px(p.X), py(p.Y), c, dash)
			}
			if s.Markers || len(se.Points) == 1 {
				r.fill(int(px(p.X))-4, int(py(p.Y))-4, int(px(p.X))+5, int(py(p.Y))+5, c)
			}
			last = &se.Points[j]
		}
		lx := (padL + (i%4)*200) * scale
		ly := (chartH - 34 + (i/4)*16) * scale
		r.line(float64(lx), float64(ly+7), float64(lx+36), float64(ly+7), c, dash)
		r.text(lx+44, ly, en(se.En, se.Name, fmt.Sprintf("series %d", i+1)), ink, 2)
	}
	if !l.anyValid {
		msg := "no valid observations (gap, not zero)"
		r.text((padL+plotW/2)*scale-textWidth(msg, 2)/2, (padT+plotH/2)*scale, msg, muted, 2)
	}
	var buf bytes.Buffer
	_ = (&png.Encoder{CompressionLevel: png.BestCompression}).Encode(&buf, r.img)
	return buf.Bytes()
}
