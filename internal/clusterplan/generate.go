// GenerateOptions are the wizard answers that shape a generated inventory.
type GenerateOptions struct {
	Name      string
	Addresses []string // node IPs in order; n1, n2, ...
	Video     bool
	Capacity  bool
}

// GenerateInventory lays out a cluster over the given nodes. Every node is
// its own fault domain (separate hosts). Quorum services use the first three
// nodes; single-instance services go to the last node, which carries the
// least quorum load; stateless roles are spread two or three wide.
func GenerateInventory(o GenerateOptions) (*Inventory, error) {
	n := len(o.Addresses)
	if n < 3 {
		return nil, fmt.Errorf("a cluster needs at least 3 nodes (got %d); use the single-node deployment for one server", n)
	}
	seen := map[string]bool{}
	inv := &Inventory{SchemaVersion: 1, Name: o.Name, Images: DefaultImages(), Env: map[string]string{"IOT_ADMIN_TENANTS": "tenant_001", "IOT_OPS_TENANTS": "tenant_001"}}
	names := make([]string, n)
	for i, a := range o.Addresses {
		a = strings.TrimSpace(a)
		if net.ParseIP(a) == nil {
			return nil, fmt.Errorf("node %d: %q is not an IP address", i+1, a)
		}
		if seen[a] {
			return nil, fmt.Errorf("node address %s is listed twice", a)
		}
		seen[a] = true
		names[i] = fmt.Sprintf("n%d", i+1)
		inv.Nodes = append(inv.Nodes, Node{Name: names[i], Address: a, FaultDomain: "host-" + names[i]})
	}
	first3 := names[:3]
	last := names[n-1]
	// span returns k nodes starting at offset, wrapping around.
	span := func(offset, k int) []string {
		out := make([]string, 0, k)
		for i := 0; i < min(k, n); i++ {
			out = append(out, names[(offset+i)%n])
		}
		return out
	}
	inv.Etcd = GroupSpec{Nodes: first3}
	inv.Postgres = PostgresSpec{Nodes: first3, Synchronous: true}
	inv.Redpanda = RedpandaSpec{Nodes: first3}
	inv.EMQX = GroupSpec{Nodes: first3}
	inv.Redis = RedisSpec{Master: names[0], Replicas: names[1:3], Sentinels: first3}
	switch {
	case n == 3:
		inv.ClickHouse = ClickHouseSpec{Shards: [][]string{first3}, Keeper: first3}
	case n < 6:
		inv.ClickHouse = ClickHouseSpec{Shards: [][]string{names[0:2], names[2:4]}, Keeper: span(1, 3)}
	default:
		inv.ClickHouse = ClickHouseSpec{Shards: [][]string{names[0:3], names[3:6]}, Keeper: span(n-3, 3)}
	}
	inv.MinIO = SingleSpec{Node: last}
	inv.Backup = SingleSpec{Node: last}
	inv.Monitoring = SingleSpec{Node: last}
	if o.Video {
		inv.Video = SingleSpec{Node: last}
	}
	if o.Capacity {
		inv.Capacity = SingleSpec{Node: last}
	}
	inv.Harness = GroupSpec{Nodes: span(1, 2)}
	workers := min(n, 3)
	inv.Platform = PlatformSpec{
		Roles: map[string]RoleSpec{
			"api":       {Nodes: span(0, 2)},
			"gateway":   {Nodes: span(1, 2)},
			"parser":    {Nodes: span(0, workers)},
			"processor": {Nodes: span(0, workers)},
			"jobs":      {Nodes: []string{names[0], last}},
		},
		Web: GroupSpec{Nodes: span(0, 2)},
	}
	inv.defaults()
	if _, err := inv.Validate(); err != nil {
		return nil, fmt.Errorf("generated layout is invalid:\n%w", err)
	}
	return inv, nil
}

// MarshalInventory writes an inventory with a short header.
func MarshalInventory(inv *Inventory) ([]byte, error) {
	b, err := yaml.Marshal(inv)
	if err != nil {
		return nil, err
	}
	header := "# Generated by scripts/cluster-up (cluster-render -generate). Edit placement here and\n# run cluster-up again; see deploy/cluster/inventory.example.yaml for every option.\n"
	return append([]byte(header), b...), nil
}

// SetCapacity turns the capacity module on (placed on the last node, beside
// the other single-instance services) or off in an inventory file. It edits
// only the top-level capacity entry, so hand-written comments survive.
func SetCapacity(path string, on bool) (string, error) {
	inv, err := Load(path)
	if err != nil {
		return "", err
	}
	b, err := os.ReadFile(path)
	if err != nil {
		return "", err
	}
	var kept []string
	lines := strings.Split(strings.TrimRight(string(b), "\n"), "\n")
	for i := 0; i < len(lines); i++ {
		if strings.HasPrefix(lines[i], "capacity:") {
			// Drop the entry and its indented block.
			for i+1 < len(lines) && (strings.HasPrefix(lines[i+1], " ") || strings.HasPrefix(lines[i+1], "\t")) {
				i++
			}
			continue
		}
		kept = append(kept, lines[i])
	}
	node := ""
	if on {
		node = inv.Capacity.Node
		if node == "" {
			node = inv.Nodes[len(inv.Nodes)-1].Name
		}
		kept = append(kept, "capacity: {node: "+node+"}")
	}
	out := strings.Join(kept, "\n") + "\n"
	check := *inv
	check.Capacity = SingleSpec{Node: node}
	if _, err = check.Validate(); err != nil {
		return "", fmt.Errorf("capacity module cannot be placed on %s:\n%w", node, err)
	}
	return node, os.WriteFile(path, []byte(out), 0o644)
}
