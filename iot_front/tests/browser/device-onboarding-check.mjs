import { spawn } from 'node:child_process'
import { mkdtemp, readFile, rm, writeFile } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import assert from 'node:assert/strict'

const profile = await mkdtemp(join(tmpdir(), 'iot-device-flow-'))
const child = spawn(process.env.IOT_TEST_BROWSER, ['--headless=new','--no-first-run','--no-default-browser-check','--disable-gpu','--remote-debugging-port=0',`--user-data-dir=${profile}`,'about:blank'], {windowsHide:true,stdio:'ignore'})
let socket
const delay = ms => new Promise(resolve => setTimeout(resolve,ms))
async function until(fn, note) { for(let i=0;i<120;i++){const value=await fn();if(value)return value;await delay(100)}throw new Error(`Browser condition timed out: ${note}`) }
try {
  const port = await until(async()=>{try{return (await readFile(join(profile,'DevToolsActivePort'),'utf8')).split('\n')[0]}catch{return null}},'Chrome debugger')
  const pages = await (await fetch(`http://127.0.0.1:${port}/json/list`)).json()
  socket = new WebSocket(pages.find(p=>p.type==='page').webSocketDebuggerUrl)
  await new Promise((resolve,reject)=>{socket.onopen=resolve;socket.onerror=reject})
  let id=0;const pending=new Map()
  socket.onmessage=event=>{const value=JSON.parse(event.data);if(value.id){const p=pending.get(value.id);pending.delete(value.id);value.error?p.reject(new Error(value.error.message)):p.resolve(value.result)}}
  const call=(method,params={})=>new Promise((resolve,reject)=>{const next=++id;pending.set(next,{resolve,reject});socket.send(JSON.stringify({id:next,method,params}))})
  const evaluate=async expression=>{const r=await call('Runtime.evaluate',{expression,returnByValue:true,awaitPromise:true});if(r.exceptionDetails)throw new Error(r.exceptionDetails.text+' '+JSON.stringify(r.exceptionDetails.exception));return r.result.value}
  const click=async text=>until(()=>evaluate(`(()=>{const e=[...document.querySelectorAll('button,label')].find(e=>(e.getAttribute('aria-label')===${JSON.stringify(text)}||e.textContent.trim()===${JSON.stringify(text)})&&e.getClientRects().length&&!e.disabled);if(!e)return false;e.click();return true})()`),text)
  const fill=async(label,value)=>until(()=>evaluate(`(()=>{const item=[...document.querySelectorAll('.el-form-item,.n-form-item')].find(e=>e.querySelector('.n-form-item-label,.el-form-item__label,label')?.textContent.trim().startsWith(${JSON.stringify(label)}));const input=item?.querySelector('input');if(!input)return false;input.value=${JSON.stringify(value)};input.dispatchEvent(new Event('input',{bubbles:true}));return true})()`),`input: ${label}`)
  const select=async(label,match)=>{await until(()=>evaluate(`(()=>{const item=[...document.querySelectorAll('.el-form-item,.n-form-item')].find(e=>e.querySelector('.n-form-item-label,.el-form-item__label,label')?.textContent.trim().startsWith(${JSON.stringify(label)}));const control=item?.querySelector('.n-base-selection');if(!control)return false;control.click();return true})()`),`select: ${label}`);await until(()=>evaluate(`(()=>{const option=[...document.querySelectorAll('.n-base-select-option')].find(e=>e.textContent.includes(${JSON.stringify(match)})&&e.getClientRects().length);if(!option)return false;option.click();return true})()`),`option: ${match}`)}
  const capture=async name=>{await evaluate('new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve)))');assert.ok(await evaluate('document.documentElement.scrollWidth<=innerWidth+2'),`${name} horizontal overflow`);if(!name.endsWith('-bottom'))assert.ok(await evaluate("(()=>{const heading=document.querySelector('.onboarding-card .step-intro h3'),content=document.querySelector('.main-content');if(!heading||!content)return false;const h=heading.getBoundingClientRect(),c=content.getBoundingClientRect();return h.top>=c.top-1&&h.top<c.bottom})()"),`${name} step heading not visible`);const shot=await call('Page.captureScreenshot',{format:'png',captureBeyondViewport:true});await writeFile(join(tmpdir(),`iot-onboarding-${name}.png`),Buffer.from(shot.data,'base64'))}
  await call('Page.enable')
  await call('Emulation.setDeviceMetricsOverride',{width:1440,height:900,deviceScaleFactor:1,mobile:false})
  await call('Page.addScriptToEvaluateOnNewDocument',{source:`localStorage.setItem('iot_token',${JSON.stringify(process.env.IOT_TEST_TOKEN)});localStorage.setItem('iot_tenant','tenant');localStorage.setItem('iot_role','admin');localStorage.setItem('iot_user','browser-test');`})
  await call('Page.navigate',{url:process.env.IOT_TEST_ORIGIN})
  await click('设备管理')
  await click('接入设备')
  await capture('desktop-start')
  await click('首次接入新型号')
  await capture('desktop-new-template')
  await evaluate("document.querySelector('.onboarding-optional summary').click()")
  await until(()=>evaluate("document.querySelector('.onboarding-optional input')?.getClientRects().length>0"),'optional template details')
  await evaluate("document.querySelector('.main-content').scrollTop=document.querySelector('.main-content').scrollHeight")
  await capture('desktop-template-optional-bottom')
  await fill('模板名称','浏览器新型号')
  await select('设备通信协议','标准设备上报')
  await click('下一步')
  await until(()=>evaluate(`document.querySelector('.onboarding-workspace')?.textContent.includes('填写设备信息') && !!document.querySelector('.onboarding-workspace input[placeholder="例如 一层东侧烟感"]')`),'new template saved')
  await capture('desktop-device-info')
  await evaluate("document.querySelector('.onboarding-optional summary').click()")
  await until(()=>evaluate("document.querySelector('.onboarding-optional textarea')?.getClientRects().length>0"),'optional device details')
  await evaluate("document.querySelector('.main-content').scrollTop=document.querySelector('.main-content').scrollHeight")
  await capture('desktop-device-optional-bottom')
  await fill('设备名称','浏览器现场设备')
  await click('使用平台编号')
  await click('下一步')
  await until(()=>evaluate(`document.querySelector('.onboarding-workspace')?.textContent.includes('密钥只在首次创建时显示')`),'connection settings')
  await capture('desktop-connection')
  await click('保存设备并检查')
  await until(()=>evaluate(`document.querySelector('.onboarding-workspace')?.textContent.includes('等待本次设备上报')`),'saved device check')
  assert.equal(await evaluate(`document.querySelector('.onboarding-workspace')?.textContent.includes('本次解析成功')`),false)
  assert.equal(await evaluate(`document.querySelector('.onboarding-workspace')?.textContent.includes('设备 Secret 只显示这一次')`),true)
  assert.equal(await evaluate(`Object.values(localStorage).some(v=>typeof v==='string'&&v.includes('ds_'))`),false)
  await capture('desktop-check')
  await call('Emulation.setDeviceMetricsOverride',{width:390,height:844,deviceScaleFactor:1,mobile:true})
  await evaluate('new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve)))')
  assert.ok(await evaluate(`document.querySelector('.onboarding-workspace').getBoundingClientRect().width<=390`),'narrow workspace overflow')
  assert.ok(await evaluate(`document.documentElement.scrollWidth<=390`),'narrow page horizontal overflow')
  await capture('mobile-check')
  assert.ok(await evaluate(`(()=>{const content=document.querySelector('.main-content');content.scrollTop=content.scrollHeight;const actions=document.querySelector('.onboarding-actions'),last=actions?.querySelector('button:last-child'),r=last?.getBoundingClientRect(),bottom=content.getBoundingClientRect().bottom;return !!r&&r.top>=content.getBoundingClientRect().top&&r.bottom<=bottom+1})()`),'mobile check actions unreachable after scrolling')
  await capture('mobile-check-bottom')
  await call('Page.navigate',{url:process.env.IOT_TEST_ORIGIN})
  await click('设备管理')
  await until(()=>evaluate(`Boolean(document.querySelector('.n-data-table')) && !document.querySelector('.onboarding-workspace')`),'default device list with saved draft')
  await click('接入设备')
  await until(()=>evaluate(`document.querySelector('.onboarding-workspace')?.textContent.includes('检查设备数据') && document.querySelector('.onboarding-workspace')?.textContent.includes('浏览器现场设备')`),'draft recovery')
  assert.equal(await evaluate(`document.querySelector('.onboarding-workspace').textContent.includes('设备 Secret 只显示这一次')`),false)
  await click('进入日常管理')
  await until(()=>evaluate(`document.querySelector('.n-data-table')?.textContent.includes('浏览器现场设备')`),'daily device list')
  await click('接入设备')
  await capture('mobile-existing-template')
  await select('选择设备模板','浏览器新型号')
  await click('下一步')
  await capture('mobile-device-info')
  await fill('设备名称','同型号第二台设备')
  await fill('实际设备编号','site-device-02')
  await click('下一步')
  await capture('mobile-connection')
  await click('保存设备并检查')
  await until(()=>evaluate(`document.querySelector('.onboarding-workspace')?.textContent.includes('site-device-02') && document.querySelector('.onboarding-workspace')?.textContent.includes('等待本次设备上报')`),'existing template flow')
  assert.ok(await evaluate(`document.querySelector('.onboarding-workspace').textContent.includes('mqtts://devices.example.test:8883')`),'MQTT connection information')
  await capture('mobile-existing-check')
  await click('进入日常管理')
  await click('接入设备')
  await click('首次接入新型号')
  await capture('mobile-new-template')
  await fill('模板名称','等待厂家协议的型号')
  await click('前往设备通信协议工作区')
  await until(()=>evaluate(`document.body.innerText.includes('设备通信协议') && !document.querySelector('.onboarding-workspace')`),'protocol workspace navigation')
  await click('设备管理')
  await until(()=>evaluate(`Boolean(document.querySelector('.n-data-table')) && !document.querySelector('.onboarding-workspace')`),'device list after protocol detour')
  await click('接入设备')
  await until(()=>evaluate(`document.querySelector('.onboarding-workspace input[placeholder="例如 厂商及型号"]')?.value==='等待厂家协议的型号'`),'return to incomplete draft')
  await click('主设备下的子设备')
  await until(()=>evaluate(`document.querySelector('.onboarding-workspace')?.textContent.includes('暂无可选主设备')`),'empty child onboarding guidance')
  await capture('mobile-child-empty')
  console.log('PASS: real browser and isolated Go API, new and existing template, device registration, MQTT information, check, secret handling, protocol detour, refresh recovery and 390px layout')
} finally {
  socket?.close()
  child.kill()
  try { await rm(profile,{recursive:true,force:true,maxRetries:10,retryDelay:200}) } catch { /* Browser teardown must not hide the assertion. */ }
}
